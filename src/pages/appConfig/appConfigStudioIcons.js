export const getToolboxIcon = (key, blockType) => {
  const normalized = String(key || blockType || '').toLowerCase();
  if (normalized.includes('hero') && !normalized.includes('carousel')) return StudioIcons.HeroBanner;
  if (normalized.includes('carousel') || normalized.includes('slider')) return StudioIcons.BannerSlider;
  if (normalized.includes('promo') || normalized.includes('offer')) return StudioIcons.PromoBanner;
  if (normalized.includes('bento') || normalized.includes('split') || normalized.includes('card') || normalized.includes('feature')) return StudioIcons.PromoCards;
  if (normalized.includes('product') || normalized.includes('shelf') || normalized.includes('deal')) return StudioIcons.ProductList;
  if (normalized.includes('category') || normalized.includes('showcase')) return StudioIcons.CategoryGrid;
  if (normalized.includes('shop') || normalized.includes('business') || normalized.includes('brand') || normalized.includes('vendor') || normalized.includes('ad') || normalized.includes('stat') || normalized.includes('health') || normalized.includes('b2b')) return StudioIcons.Business;
  if (normalized.includes('icon') || normalized.includes('pill') || normalized.includes('chip') || normalized.includes('quick')) return StudioIcons.IconGrid;
  if (normalized.includes('coupon') || normalized.includes('discount')) return StudioIcons.CouponStrip;
  if (normalized.includes('header') || normalized.includes('address')) return StudioIcons.Pages;
  if (normalized.includes('search')) return StudioIcons.Search;
  if (normalized.includes('image') || normalized.includes('banner')) return StudioIcons.ImageBanner;
  if (normalized.includes('list') || normalized.includes('info') || normalized.includes('title')) return StudioIcons.Pages;
  return StudioIcons.CategoryGrid;
};